/**
 * Filter & sort leaderboard consultants
 */
export function getLeaderboardData({
  period = "this_month",
  city = "All Cities",
  metric = "qualified_inquiries",
} = {}) {
  let list = [...CONSULTANT_LEADERBOARD_DATA];

  // City filter
  if (city && city !== "All Cities") {
    list = list.filter((c) => c.city.toLowerCase() === city.toLowerCase());
  }

  // Sort by metric
  list.sort((a, b) => {
    if (metric === "active_listings") {
      return b.activeListings - a.activeListings;
    }
    if (metric === "response_rate") {
      return b.responseRate - a.responseRate;
    }
    // Default: qualified inquiries for the period
    const aVal = a.inquiries[period] ?? a.inquiries.this_month;
    const bVal = b.inquiries[period] ?? b.inquiries.this_month;
    return bVal - aVal;
  });

  // Assign updated rank based on sorted order
  return list.map((item, index) => ({
    ...item,
    currentRank: index + 1,
    inquiryCount: item.inquiries[period] ?? item.inquiries.this_month,
  }));
}

