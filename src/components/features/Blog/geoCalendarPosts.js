/** Map money landing path → related calendar blog posts */
export function relatedBlogLinksForPath(pathname) {
  const path = String(pathname || "").split("?")[0];
  return GEO_CALENDAR_POSTS.filter((p) => p.moneyUrl === path || path.includes(String(p.moneyUrl || "").replace(/^\//, "")))
    .map((p) => ({ label: p.title, href: p.slug }))
    .slice(0, 3);
}

export function relatedBlogLinksForPlace(placeSlug) {
  const place = String(placeSlug || "").toLowerCase();
  if (!place) return [];
  return GEO_CALENDAR_POSTS.filter((p) => {
    const money = String(p.moneyUrl || "");
    return money.includes(`-${place}`) || money.endsWith(`/${place}`) || money.includes(place);
  })
    .map((p) => ({ label: p.title, href: p.slug }))
    .slice(0, 4);
}
